----------------------------------------------------------------------------------
-- קובץ       : debounce_rst.vhd
-- תפקיד      : דיבאונסר (Debouncer) + זיהוי חזית (Edge Detector) לכפתור אחד
--
-- תיאור כללי:
--   הכפתור המכני הוא רכיב אסינכרוני ל־clk ועלול לסבול מקפיצות (bouncing)
--   בזמן לחיצה/שחרור. מודול זה:
--
--   1. מסנכרן את אות הכפתור לשעון המערכת (clk) באמצעות שרשרת FFs.
--   2. מבצע דיבאונס – דורש שהאות יהיה יציב למשך זמן מוגדר.
--   3. מפיק פולס של מחזור שעון אחד בלבד כאשר מזוהה חזית עולה תקינה (לחיצה).
--
-- הערות חשובות:
--   • אין Reset פנימי במודול זה.
--   • האתחול מתבסס על אתחול אותות ב־FPGA (Power-Up Initialization).
--   • אם נדרש איפוס דטרמיניסטי – מומלץ להשתמש בגרסה עם reset.
----------------------------------------------------------------------------------

LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;

ENTITY debounce_rst IS
    PORT (
        clk  : IN  STD_LOGIC;  -- שעון מערכת (לדוגמה: 100MHz)
        btn  : IN  STD_LOGIC;  -- כניסת כפתור גולמית (אסינכרונית)
        edge : OUT STD_LOGIC   -- פולס של מחזור שעון אחד בעת לחיצה תקינה
    );
END debounce_rst;

ARCHITECTURE Behavioral OF debounce_rst IS

    ----------------------------------------------------------------------------
    -- שרשרת סנכרון (Synchronizer):
    --   c0 <= דגימה ראשונה של הכפתור
    --   c1 <= דגימה מסונכרנת
    --   c2 <= דגימה מושהית נוספת
    --
    -- שימוש ב־3 FFs:
    --   • הפחתת סכנת מטא־סטביליות
    --   • קבלת דגימה "ישנה" לצורך דיבאונס וזיהוי חזית
    ----------------------------------------------------------------------------
    SIGNAL c0, c1, c2 : STD_LOGIC := '0';

    ----------------------------------------------------------------------------
    -- זמן דיבאונס:
    --   בהנחה ש־clk = 100MHz:
    --   500,000 מחזורים × 10ns = 5ms
    --
    -- אם תדר השעון שונה – חובה לעדכן ערך זה!
    ----------------------------------------------------------------------------
    CONSTANT DEBOUNCE_TIME : INTEGER := 500000;

    -- מונה שסופר כמה זמן האות נשאר יציב
    SIGNAL counter : INTEGER RANGE 0 TO DEBOUNCE_TIME := 0;

    -- ערך הכפתור לאחר דיבאונס (אות "נקי")
    SIGNAL btn_stable : STD_LOGIC;

BEGIN

    ----------------------------------------------------------------------------
    -- תהליך סינכרון + דיבאונס (מתוזמן לשעון)
    ----------------------------------------------------------------------------
    PROCESS (clk)
    BEGIN
        IF rising_edge(clk) THEN

            --------------------------------------------------------------------
            -- שלב 1: סנכרון הכפתור לשעון המערכת
            --------------------------------------------------------------------
            c0 <= btn;
            c1 <= c0;
            c2 <= c1;

            --------------------------------------------------------------------
            -- שלב 2: דיבאונס
            --
            -- אם יש שינוי בין דגימות עוקבות → הכפתור עדיין "קופץ"
            -- ולכן מאפסים את המונה.
            --------------------------------------------------------------------
            IF c0 /= c1 THEN
                counter <= 0;

            -- אם אין שינוי, אבל עדיין לא עבר זמן הדיבאונס המלא
            ELSIF counter < DEBOUNCE_TIME THEN
                counter <= counter + 1;

            -- אם האות יציב מספיק זמן → מאשרים אותו כערך תקין
            ELSE
                btn_stable <= c2;
            END IF;
        END IF;
    END PROCESS;

    ----------------------------------------------------------------------------
    -- זיהוי חזית עולה (Edge Detection):
    --
    -- edge = '1' למשך מחזור שעון אחד כאשר:
    --   • btn_stable = '1'  (כפתור נחשב לחוץ)
    --   • c1 = '0'          (במחזור הקודם היה 0)
    --
    -- כלומר: זיהוי מעבר 0 → 1 לאחר דיבאונס
    ----------------------------------------------------------------------------
    edge <= btn_stable AND NOT c1;

END Behavioral;
